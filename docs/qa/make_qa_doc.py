def shade(cell, hex_):
    tcPr = cell._tc.get_or_add_tcPr(); shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), hex_); tcPr.append(shd)

def p(text, bold=False, italic=False, size=None, after=6):
    par = doc.add_paragraph(); r = par.add_run(text); r.bold = bold; r.italic = italic
    if size: r.font.size = Pt(size)
    par.paragraph_format.space_after = Pt(after); return par

def bullets(items):
    for it in items:
        par = doc.add_paragraph(style='List Bullet'); par.paragraph_format.space_after = Pt(2)
        if isinstance(it, tuple):
            r = par.add_run(it[0]); r.bold = True; par.add_run(it[1])
        else: par.add_run(it)

def table(headers, rows, widths=None, header_fill='DCEEDF', font=9.5):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]; c.text = ''; r = c.paragraphs[0].add_run(h); r.bold = True; r.font.size = Pt(font); shade(c, header_fill)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            lines = val if isinstance(val, list) else [val]
            for j, line in enumerate(lines):
                par = cells[i].paragraphs[0] if j == 0 else cells[i].add_paragraph()
                par.paragraph_format.space_after = Pt(1)
                r = par.add_run(line); r.font.size = Pt(font)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths): row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

